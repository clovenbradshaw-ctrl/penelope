// gym/check-tapestry.mjs — keeps TAPESTRY.md (and the copy on the README's
// front page) true to the repo. The tapestry is the PRESENT TENSE of how
// generation works; GLAUCA-EOT.md is the append-only history that explains it.
//
//   node gym/check-tapestry.mjs           verify (exit 1 when the picture is stale)
//   node gym/check-tapestry.mjs --stamp   after RE-WEAVING: verify coverage,
//                                          copy the block into README.md, and
//                                          record the hashes of the watched files
//
// It fails when:
//   (1) COVERAGE   an organ, adapter, gym script, ladder file, apps/record.json
//                  or gym route is not named in the tapestry;
//   (2) DANGLING   the tapestry names a file that does not exist here and is
//                  not declared <!-- tapestry:external: ... --> (read at home,
//                  never forked) or <!-- tapestry:generated: ... --> (a runtime
//                  artifact);
//   (3) README     the block on README.md differs from TAPESTRY.md's;
//   (4) DRIFT      a watched file changed since the last stamp — somebody
//                  changed a process; re-weave that thread, then --stamp.
// Falsifying control: a commit that re-routes a door or adds an organ while
// this check passes on a stale picture would show the check is decorative.
// (selftest below mutates an in-memory repo to prove each failure fires.)
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const SCHEMA = "TapestryStamp@1";
const BEGIN = "<!-- tapestry:begin -->";
const END = "<!-- tapestry:end -->";
const SKIP = new Set([".git", "node_modules"]);
// generated by --stamp from the block, served by the gym at /tapestry.html
export const GENERATED_PAGE = "gym/tapestry.html";
const pageOf = (block) => {
  const art = block.replace(/^\s*```text\n/, "").replace(/\n```\s*$/, "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  return `<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Penelope Tapestry</title>
<!-- GENERATED by gym/check-tapestry.mjs --stamp from TAPESTRY.md — do not edit -->
<style>:root{--bg:#f6f1e7;--fg:#2b2118}@media(prefers-color-scheme:dark){:root{--bg:#1c1712;--fg:#e8dcc6}}
body{margin:0;background:var(--bg);color:var(--fg);font:14px/1.25 ui-monospace,Menlo,monospace;display:flex;justify-content:center;padding:24px 16px}
pre{margin:0;overflow-x:auto;font-size:clamp(9px,1.9vw,15px)}</style><pre>${art}</pre>
`;
};

const walk = (root, dir = "") => {
  const out = [];
  for (const e of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const rel = path.posix.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(root, rel));
    else out.push(rel);
  }
  return out;
};

export const blockOf = (text) => {
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  return a < 0 || b < a ? null : text.slice(a + BEGIN.length, b);
};
const listOf = (text, key) => {
  const m = text.match(new RegExp(`<!-- tapestry:${key}:([^>]*)-->`));
  return m ? m[1].trim().split(/\s+/).filter(Boolean) : [];
};

// What the picture must cover, and what it watches for drift.
export const coverable = (files) => files.filter((f) =>
  (/^organs\/[^/]+\.mjs$/.test(f)) || (/^organs\/generation\/.+\.mjs$/.test(f)) ||
  (/^gym\/[^/]+\.(mjs|html)$/.test(f) && f !== GENERATED_PAGE) || (/^ladder\/[^/]+$/.test(f)) || f === "apps/record.json");
export const watched = (files) => files.filter((f) =>
  (/^(organs|gym|ladder)\//.test(f) && f !== "gym/check-tapestry.mjs" && !f.endsWith(".jsonl") && f !== GENERATED_PAGE) || f === "apps/record.json" || f === "LOOMS.md");

const sha = (root, f) => createHash("sha256").update(fs.readFileSync(path.join(root, f))).digest("hex");

export function inspect(root) {
  const problems = [];
  const read = (f) => { try { return fs.readFileSync(path.join(root, f), "utf8"); } catch { return null; } };
  const tap = read("TAPESTRY.md");
  if (tap === null) return { problems: ["TAPESTRY.md is missing"], block: null };
  const block = blockOf(tap);
  if (block === null) return { problems: ["TAPESTRY.md has no tapestry:begin/end block"], block: null };
  const files = walk(root);
  const external = new Set(listOf(tap, "external")), generated = new Set(listOf(tap, "generated"));

  // (1) coverage — by basename; organs/ flat files may be named by stem; a
  // `dir/*.ext` glob covers that directory; gym routes are read from server.mjs.
  const globs = [...block.matchAll(/([\w.-]+\/)+\*\.\w+/g)].map((m) => m[0]);
  for (const f of coverable(files)) {
    const base = path.posix.basename(f), stem = base.replace(/\.[^.]+$/, "");
    const flatOrgan = /^organs\/[^/]+\.mjs$/.test(f);
    const globbed = globs.some((g) => f.startsWith(g.slice(0, g.lastIndexOf("/") + 1)) && f.endsWith(g.slice(g.lastIndexOf("*") + 1)));
    if (!(block.includes(base) || (flatOrgan && block.includes(stem)) || globbed)) problems.push(`COVERAGE: ${f} is not in the tapestry`);
  }
  const server = read("gym/server.mjs") ?? "";
  for (const m of server.matchAll(/pathname === "(\/[^"]+)"/g)) {
    if (m[1] !== "/" && !block.includes(m[1])) problems.push(`COVERAGE: route ${m[1]} (gym/server.mjs) is not in the tapestry`);
  }

  // (2) dangling references
  const known = (tok) => {
    const base = path.posix.basename(tok);
    return files.some((f) => f === tok || f.endsWith("/" + tok)) || external.has(base) || generated.has(base);
  };
  const toks = new Set([...block.matchAll(/[A-Za-z0-9_][A-Za-z0-9_./-]*\.(?:mjs|js|json|jsonl|ipynb|md|html)\b/g)].map((m) => m[0]));
  for (const t of toks) if (!known(t)) problems.push(`DANGLING: the tapestry names ${t}, which is not here (declare it external/generated or fix the picture)`);

  // (3) README carries the same block
  const readme = read("README.md");
  if (readme === null || blockOf(readme) === null) problems.push("README: no tapestry block on the front page (run --stamp)");
  else if (blockOf(readme) !== block) problems.push("README: the front-page tapestry differs from TAPESTRY.md (run --stamp)");

  // (4) drift since the last stamp
  const stampRaw = read(".tapestry-stamp.json");
  if (stampRaw === null) problems.push("DRIFT: no stamp yet (run --stamp after weaving)");
  else {
    const stamp = JSON.parse(stampRaw), now = new Set(watched(files));
    for (const f of now) {
      if (!(f in stamp.files)) problems.push(`DRIFT: ${f} was added since the weave — re-weave, then --stamp`);
      else if (stamp.files[f] !== sha(root, f)) problems.push(`DRIFT: ${f} changed since the weave — re-weave that thread, then --stamp`);
    }
    for (const f of Object.keys(stamp.files)) if (!now.has(f)) problems.push(`DRIFT: ${f} was removed since the weave — re-weave, then --stamp`);
  }
  return { problems, block, files };
}

export function stamp(root) {
  const r = inspect(root);
  const hard = r.problems.filter((p) => /^(COVERAGE|DANGLING)|no tapestry/.test(p));
  if (hard.length) return { ok: false, problems: hard };
  const readmePath = path.join(root, "README.md");
  let readme = fs.readFileSync(readmePath, "utf8");
  if (blockOf(readme) === null) return { ok: false, problems: ["README.md has no tapestry:begin/end markers to fill"] };
  const a = readme.indexOf(BEGIN) + BEGIN.length;
  readme = readme.slice(0, a) + r.block + readme.slice(readme.indexOf(END));
  fs.writeFileSync(readmePath, readme);
  fs.mkdirSync(path.join(root, "gym"), { recursive: true });
  fs.writeFileSync(path.join(root, GENERATED_PAGE), pageOf(r.block));
  const files = Object.fromEntries(watched(r.files).sort().map((f) => [f, sha(root, f)]));
  fs.writeFileSync(path.join(root, ".tapestry-stamp.json"), JSON.stringify({ schema: SCHEMA, woven: new Date().toISOString().slice(0, 10), files }, null, 2) + "\n");
  return { ok: true, problems: [], stamped: Object.keys(files).length };
}

// ── selftest: each failure must fire on a constructed violation (a check
// never seen firing is a comment, not a check — GL-QA-01) ──
export function selftest() {
  const os = fs, tmp = fs.mkdtempSync(path.join(fs.realpathSync(process.env.TMPDIR ?? "/tmp"), "tapestry-"));
  const put = (f, t) => { fs.mkdirSync(path.dirname(path.join(tmp, f)), { recursive: true }); fs.writeFileSync(path.join(tmp, f), t); };
  const art = "```text\norgans: alpha beta.mjs server.mjs routes /api/x ladder/*.json look.js\n```\n";
  put("TAPESTRY.md", `<!-- tapestry:external: look.js -->\n${BEGIN}\n${art}${END}\n`);
  put("README.md", `# r\n${BEGIN}\n${art}${END}\n`);
  put("organs/alpha.mjs", "a"); put("organs/beta.mjs", "b"); put("ladder/r1.json", "{}");
  put("gym/server.mjs", 'if (u.pathname === "/api/x") {}');
  const out = []; const t = (name, ok) => { out.push([name, ok]); if (!ok) throw new Error("tapestry selftest failed: " + name); };
  t("stamps a covered picture", stamp(tmp).ok);
  t("a clean repo passes", inspect(tmp).problems.length === 0);
  put("organs/gamma.mjs", "g"); t("a new organ not in the picture is COVERAGE", inspect(tmp).problems.some((p) => p.startsWith("COVERAGE: organs/gamma.mjs")));
  fs.rmSync(path.join(tmp, "organs/gamma.mjs"));
  put("gym/server.mjs", 'if (u.pathname === "/api/x") {} if (u.pathname === "/api/y") {}'); t("a new route not in the picture is COVERAGE", inspect(tmp).problems.some((p) => p.includes("route /api/y")));
  put("gym/server.mjs", 'if (u.pathname === "/api/x") {}'); t("restoring the route passes the drift check", inspect(tmp).problems.length === 0);
  put("organs/alpha.mjs", "a-changed"); t("a changed watched file is DRIFT", inspect(tmp).problems.some((p) => p.startsWith("DRIFT: organs/alpha.mjs")));
  put("organs/alpha.mjs", "a");
  put("TAPESTRY.md", `<!-- tapestry:external: look.js -->\n${BEGIN}\n${art.replace("look.js", "look.js ghost.mjs")}${END}\n`);
  t("a named file that does not exist is DANGLING", inspect(tmp).problems.some((p) => p.startsWith("DANGLING: the tapestry names ghost.mjs")));
  t("an unreadable-to-stamp picture refuses to stamp", stamp(tmp).ok === false);
  put("TAPESTRY.md", `<!-- tapestry:external: look.js -->\n${BEGIN}\n${art}${END}\n`);
  put("README.md", `# r\n${BEGIN}\nstale${END}\n`); t("a stale README block is caught", inspect(tmp).problems.some((p) => p.startsWith("README:")));
  fs.rmSync(tmp, { recursive: true, force: true });
  return { schema: SCHEMA, checks: out.length, ok: true };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
  const arg = process.argv[2];
  if (arg === "--selftest") { console.log(JSON.stringify(selftest())); }
  else if (arg === "--stamp") {
    const r = stamp(root);
    if (!r.ok) { console.error("cannot stamp:\n  " + r.problems.join("\n  ")); process.exit(1); }
    console.log(`tapestry re-stamped: ${r.stamped} watched files, README block synced`);
  } else {
    const { problems } = inspect(root);
    if (problems.length) { console.error("TAPESTRY IS STALE:\n  " + problems.join("\n  ") + "\n\nre-weave TAPESTRY.md, then: node gym/check-tapestry.mjs --stamp\nand APPEND the change to GLAUCA-EOT.md"); process.exit(1); }
    console.log("tapestry true to the repo");
  }
}
